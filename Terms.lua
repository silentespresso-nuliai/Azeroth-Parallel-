--   职业 token 就是 UnitClass 的第二个返回值，例如 "DRUID"、"PALADIN"。
--   流派 id 必须和 Flavor.lua 里 FlavorData[职业].factions[].id 完全一致，
--   写错了不会报错，只是典籍里查不到这组词条。
--
--   每条词条有 4 个字段：
--     category（分类）：变形 / 技能 / 天赋 / 其他，相同分类会自动归在一起
